import { markdownToDoc, toMarkdown, toHtml, toDocxDocumentXml, uniqueSheetNames } from '../exportDoc.js'

describe('exports', () => {
  const md = '# Profile u1\n\nRuleset: Test (`R001`)\n\n## Unified record\n\n| Field | Value |\n| --- | --- |\n| `ssot__FirstName__c` | Greg |\n| a \\| b | c |\n\n- one\n- **two**\n\n```sql\nSELECT 1\n```\n'
  it('reads the extension\'s Markdown back into blocks', () => {
    const doc = markdownToDoc(md)
    expect(doc.title).toBe('Profile u1')
    expect(doc.blocks.map((b) => b.type)).toEqual(['p', 'h', 'table', 'list', 'code'])
    expect(doc.blocks[0].text).toBe('Ruleset: Test (R001)')
    expect(doc.blocks[2]).toEqual({ type: 'table', columns: ['Field', 'Value'], rows: [['ssot__FirstName__c', 'Greg'], ['a | b', 'c']] })
    expect(doc.blocks[3].items).toEqual(['one', 'two'])
    expect(doc.blocks[4]).toEqual({ type: 'code', text: 'SELECT 1', lang: 'sql' })
  })
  it('writes Markdown, HTML and Word with lists', () => {
    const doc = markdownToDoc(md)
    expect(toMarkdown(doc)).toContain('- one\n- two')
    expect(toMarkdown(doc)).toContain('Generated by Data Cloud Inspector')
    expect(toHtml(doc)).toContain('<ul><li>one</li><li>two</li></ul>')
    expect(toHtml(doc)).toContain('<td>a | b</td>')
    expect(toDocxDocumentXml(doc)).toContain('• two')
  })
  it('keeps Excel sheet names valid and unique', () => {
    expect(uniqueSheetNames(['Fields', 'Fields', 'a/b:c*'])).toEqual(['Fields', 'Fields(2)', 'a_b_c_'])
  })
})
